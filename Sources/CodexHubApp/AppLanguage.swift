        defaults.string(forKey: "appLanguage").flatMap(Self.init(rawValue:)) ?? .system
    }
    func save(to defaults: UserDefaults) { defaults.set(rawValue, forKey: "appLanguage") }

    var resolved: AppLanguage {
        self == .system ? (Locale.preferredLanguages.first?.hasPrefix("ko") == true ? .korean : .english) : self
    }
    func text(_ value: String) -> String {
        if resolved == .korean { return Self.translations[value] ?? value }
        return Self.englishTranslations[value] ?? value
